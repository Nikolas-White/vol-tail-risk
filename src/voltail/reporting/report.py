def oracle_section(cfg: dict[str, Any], forecasts: dict[str, pd.DataFrame]) -> str:
    """Synthetic only: score forecasts against the *true* conditional variance."""
    from voltail.evaluation.losses import qlike_normalised

    raw_dir = Path(cfg["paths"]["raw_dir"])
    rows = []
    for a, fc in forecasts.items():
        p = raw_dir / f"truth_{a}.parquet"
        if not p.exists():
            continue
        tv = pd.read_parquet(p)["true_var"].reindex(fc.index)
        for m in cfg["models"]["vol"]:
            c = f"var1_{m}"
            if c in fc:
                ok = fc[c].notna() & tv.notna()
                rows.append(
                    {
                        "asset": a,
                        "model": m,
                        "qlike_vs_truth": float(qlike_normalised(tv[ok], fc.loc[ok, c]).mean()),
                        "corr": float(np.corrcoef(tv[ok], fc.loc[ok, c])[0, 1]),
                    }
                )
    if not rows:
        return ""
    d = pd.DataFrame(rows)
    t = (
        d.groupby("model")
        .agg(
            mean_qlike_vs_true_variance=("qlike_vs_truth", "mean"),
            mean_corr_with_true_variance=("corr", "mean"),
        )
        .sort_values("mean_qlike_vs_true_variance")
    )
    t.index = [lab(m) for m in t.index]
    t.index.name = "model"
    return (
        "\n### Oracle check (synthetic only): next-day forecasts vs the TRUE conditional variance\n\n"
        + md(t.reset_index(), ".4f")
        + "\n"
    )
