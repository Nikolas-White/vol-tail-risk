"""Compute every small worked example used in docs/LEARNING_GUIDE.md.

The guide promises that no number in the docs is typed by hand; the toy examples
are no exception. Run ``python scripts/learning_examples.py`` and compare with the
guide (output also written to docs/learning_examples_output.md).
"""

from __future__ import annotations

import numpy as np
from scipy import stats

from voltail.config import PROJECT_ROOT
from voltail.evaluation.forecast_tests import diebold_mariano
from voltail.evaluation.losses import fz0, qlike, qlike_normalised
from voltail.evaluation.var_tests import christoffersen_ind, kupiec_pof, traffic_light
from voltail.models.distributions import (
    gpd_tail_es,
    gpd_tail_quantile,
    normal_es,
    std_t_es,
    std_t_quantile,
)
from voltail.models.ols import ols

out: list[str] = ["# Worked-example numbers (generated by scripts/learning_examples.py)\n"]


def show(title: str, lines: list[str]) -> None:
    out.append(f"## {title}\n")
    out.extend(f"- {line}" for line in lines)
    out.append("")


# EWMA
lam, s2, r = 0.94, 1.0**2, -3.0
s2_new = lam * s2 + (1 - lam) * r**2
show(
    "EWMA update",
    [
        f"sigma_t = 1.00%, r_t = -3.00%, lambda = 0.94 -> sigma2_t+1 = 0.94*1 + 0.06*9 = {s2_new:.4f} -> sigma_t+1 = {np.sqrt(s2_new):.4f}%"
    ],
)

# GARCH(1,1)
w, a, b = 0.02, 0.08, 0.90
s2_next = w + a * r**2 + b * s2
uncond = w / (1 - a - b)
hl = np.log(0.5) / np.log(a + b)
show(
    "GARCH(1,1) update",
    [
        f"omega=0.02, alpha=0.08, beta=0.90, sigma2_t=1, r_t=-3 -> sigma2_t+1 = 0.02 + 0.08*9 + 0.90*1 = {s2_next:.4f} (sigma = {np.sqrt(s2_next):.4f}%)",
        f"long-run variance omega/(1-alpha-beta) = {uncond:.4f} -> long-run daily vol {np.sqrt(uncond):.4f}%, annualized {np.sqrt(252 * uncond):.2f}%",
        f"half-life of a shock = ln(0.5)/ln(0.98) = {hl:.2f} days",
        "10-day-ahead variance: "
        + ", ".join(
            f"h={h}: {uncond + (a + b) ** (h - 1) * (s2_next - uncond):.4f}" for h in (1, 2, 5, 10)
        ),
    ],
)

# GJR leverage
g = 0.10
up = w + 0.03 * 9 + 0.90 * 1
down = w + (0.03 + g) * 9 + 0.90 * 1
show(
    "GJR leverage effect",
    [
        f"alpha=0.03, gamma=0.10: after +3% -> sigma2 = {up:.4f}; after -3% -> sigma2 = {down:.4f} ({down / up - 1:.1%} higher)"
    ],
)

# VaR / ES normal vs t
sigma = 1.5
z99 = -stats.norm.ppf(0.01)
t99 = -std_t_quantile(0.01, 4)
show(
    "VaR and ES, normal vs Student-t(4), sigma = 1.5%",
    [
        f"normal 99% VaR = 2.326 * 1.5 = {z99 * sigma:.4f}%;  ES = {normal_es(0.01) * sigma:.4f}%",
        f"t(4) (unit variance) 99% VaR = {t99 * sigma:.4f}%;  ES = {std_t_es(0.01, 4) * sigma:.4f}%",
        f"normal 97.5% ES = {normal_es(0.025) * sigma:.4f}% vs normal 99% VaR = {z99 * sigma:.4f}% (Basel's 97.5% ES ~ 99% VaR under normality)",
    ],
)

# Kupiec / Christoffersen / traffic light
hit = np.zeros(250, dtype=int)
hit[[10, 50, 120, 121, 122, 200, 230]] = 1
lr_k, p_k = kupiec_pof(hit, 0.01)
lr_i, p_i = christoffersen_ind(hit)
show(
    "Kupiec and Christoffersen on 250 days with 7 exceedances (three in a row)",
    [
        f"expected 2.5 exceedances; Kupiec LR = {lr_k:.4f}, p = {p_k:.4f}",
        f"Christoffersen independence LR = {lr_i:.4f}, p = {p_i:.4f}",
        f"Basel zone for 7 exceptions in 250 days: {traffic_light(7, 250, 0.01)}; for 4: {traffic_light(4, 250, 0.01)}; for 10: {traffic_light(10, 250, 0.01)}",
        "Binomial(250, 1%) P(X <= k): "
        + ", ".join(f"k={k}: {stats.binom.cdf(k, 250, 0.01):.4f}" for k in (4, 5, 9, 10)),
    ],
)

# QLIKE
proxy = np.array([4.0])
show(
    "QLIKE vs MSE when the true variance is 4",
    [
        f"forecast 2 (too low by half): QLIKE_norm = {qlike_normalised(proxy, np.array([2.0]))[0]:.4f}; MSE = {(4 - 2) ** 2:.1f}",
        f"forecast 6 (too high by half): QLIKE_norm = {qlike_normalised(proxy, np.array([6.0]))[0]:.4f}; MSE = {(4 - 6) ** 2:.1f}",
        f"Patton form proxy/f + ln f for f=4: {qlike(proxy, np.array([4.0]))[0]:.4f}",
    ],
)

# OLS closed form
x = np.column_stack([np.ones(3), [1.0, 2.0, 3.0]])
y = np.array([2.0, 2.5, 4.5])
res = ols(y, x, hac_lags=0)
show(
    "OLS closed form on 3 points",
    [
        f"X = [[1,1],[1,2],[1,3]], y = [2, 2.5, 4.5] -> beta = (X'X)^-1 X'y = [{res.params[0]:.4f}, {res.params[1]:.4f}]"
    ],
)

# MLE illustration: likelihood of sigma for N(0, sigma^2)
data = np.array([-1.0, 0.5, 2.0, -0.5])
grid = [0.8, 1.0, round(float(np.sqrt(np.mean(data**2))), 4), 1.3, 1.6]
lls = [float(np.sum(stats.norm.logpdf(data, 0, s))) for s in grid]
show(
    "Maximum likelihood for a single sigma",
    [f"data = {data.tolist()}; MLE sigma = sqrt(mean(x^2)) = {np.sqrt(np.mean(data**2)):.4f}"]
    + [f"log-likelihood at sigma={s}: {ll:.4f}" for s, ll in zip(grid, lls, strict=True)],
)

# GPD tail
u, xi, beta, frac = 1.5, 0.2, 0.6, 0.10
q99 = float(gpd_tail_quantile(0.01, u, xi, beta, frac))
es99 = float(gpd_tail_es(q99, u, xi, beta))
show(
    "EVT / GPD tail",
    [
        f"threshold u = 1.5 (10% of losses above), xi = 0.2, beta = 0.6 -> 99% quantile = {q99:.4f}, ES = {es99:.4f}"
    ],
)

# FZ0
show(
    "FZ0 loss for one day (alpha = 2.5%, VaR = 2, ES = 2.5)",
    [
        f"return -1 (no exceedance): {fz0(np.array([-1.0]), np.array([2.0]), np.array([2.5]), 0.025)[0]:.4f}",
        f"return -3 (exceedance): {fz0(np.array([-3.0]), np.array([2.0]), np.array([2.5]), 0.025)[0]:.4f}",
    ],
)

# Diebold-Mariano
gen = np.random.default_rng(0)
l1 = gen.chisquare(1, 500)
l2 = l1 + 0.05 + gen.normal(0, 0.5, 500)
d = diebold_mariano(l1, l2)
show(
    "Diebold-Mariano toy",
    [
        f"500 days, model 2 worse by 0.05 on average with noise sd 0.5 -> mean diff {d.mean_diff:.4f}, DM = {d.stat:.4f}, p = {d.p_value:.4f}"
    ],
)

text = "\n".join(out)
(PROJECT_ROOT / "docs" / "learning_examples_output.md").write_text(text + "\n", encoding="utf-8")
print(text)
